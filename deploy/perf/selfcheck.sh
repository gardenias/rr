#!/usr/bin/env bash
#
# Perf-lab security-gate self-check (plan §3.2 / acceptance #1).
#
# Proves the deploy/perf stack really runs behind the RrNode G1–G7 gates:
#   S1  RR_ALLOW_INSECURE appears nowhere (source + rendered compose config)
#   S2  tokens are injected into every kv node (rendered config contains them)
#   C1  all 3 nodes report /ready
#   C2  exactly one raft leader across the cluster — inter-node AppendEntries
#       runs over mTLS, so an elected leader is the positive control
#   N1  plaintext client to the gRPC port FAILS (no TLS → no service)
#   N2  TLS client WITHOUT a client certificate FAILS (mTLS enforced)
#   P1  TLS client WITH the lab client certificate SUCCEEDS
#
# Usage (repo root or anywhere):
#   deploy/perf/selfcheck.sh           # build + up + checks + teardown
#   deploy/perf/selfcheck.sh --keep    # leave the stack running afterwards
#
# Prerequisites: docker compose v2, openssl, curl on the host. Missing certs
# (deploy/perf/certs/) and .env are auto-generated on first run.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

COMPOSE=(docker compose -f docker-compose.yml)
KEEP=0
[[ "${1:-}" == "--keep" ]] && KEEP=1

PASS=0
FAIL=0
ok()   { PASS=$((PASS + 1)); echo "  PASS  $1"; }
bad()  { FAIL=$((FAIL + 1)); echo "  FAIL  $1"; }
note() { echo "  ....  $1"; }

cleanup() {
  if [[ "$KEEP" == "0" ]]; then
    echo "==> Teardown (down -v)"
    "${COMPOSE[@]}" down -v >/dev/null 2>&1 || true
  else
    echo "==> --keep: stack left running (down: docker compose -f $SCRIPT_DIR/docker-compose.yml down -v)"
  fi
  # .env holds generated tokens — never leave it world-readable.
  [[ -f .env ]] && chmod 600 .env || true
}
trap cleanup EXIT

echo "==> [0/4] Material: certs + .env"
if [[ ! -f certs/ca.pem || ! -f certs/node1.pem || ! -f certs/client.pem ]]; then
  note "certs missing — generating via gen-certs.sh"
  ./gen-certs.sh
else
  note "certs present (delete certs/ to regenerate)"
fi
if [[ ! -f .env ]]; then
  note ".env missing — generating random local tokens"
  {
    echo "# Auto-generated by selfcheck.sh — local perf lab only, never commit."
    echo "RR_ADMIN_TOKEN=$(openssl rand -hex 24)"
    echo "RR_CLIENT_TOKEN=$(openssl rand -hex 24)"
  } > .env
  chmod 600 .env
fi

echo "==> [1/4] Static gates"
# Source level: look for an actual env assignment (`RR_ALLOW_INSECURE=` or
# YAML `RR_ALLOW_INSECURE:`) — the word alone appears in explanatory comments.
if grep -qE 'RR_ALLOW_INSECURE[=:]' docker-compose.yml; then
  bad "S1: RR_ALLOW_INSECURE assignment found in docker-compose.yml"
else
  ok "S1: no RR_ALLOW_INSECURE assignment in compose source"
fi
RENDERED="$("${COMPOSE[@]}" config 2>/dev/null)"
if grep -qi 'ALLOW_INSECURE' <<<"$RENDERED"; then
  bad "S1: RR_ALLOW_INSECURE found in rendered compose config"
else
  ok "S1: no RR_ALLOW_INSECURE in rendered config"
fi
if grep -q 'RR_ADMIN_TOKEN' <<<"$RENDERED" && grep -q 'RR_CLIENT_TOKEN' <<<"$RENDERED"; then
  ok "S2: admin + client tokens rendered into the stack env"
else
  bad "S2: tokens missing from rendered config"
fi

echo "==> [2/4] Stack up (build + wait for /ready)"
"${COMPOSE[@]}" up -d --build

deadline=$((SECONDS + 180))
ready=0
while (( SECONDS < deadline )); do
  ready=0
  for n in 1 2 3; do
    if "${COMPOSE[@]}" exec -T "kv-${n}" curl -fsS --max-time 3 http://127.0.0.1:9100/ready 2>/dev/null | grep -q '"ready":true'; then
      ready=$((ready + 1))
    fi
  done
  (( ready == 3 )) && break
  sleep 3
done
if (( ready == 3 )); then
  ok "C1: all 3 nodes /ready"
else
  bad "C1: only ${ready}/3 nodes ready after 180s"
  "${COMPOSE[@]}" ps
  echo "---- kv-1 logs (tail) ----"
  "${COMPOSE[@]}" logs --tail 30 kv-1 || true
  exit 1
fi

leaders=0
for n in 1 2 3; do
  v="$("${COMPOSE[@]}" exec -T "kv-${n}" curl -fsS --max-time 3 http://127.0.0.1:9100/metrics 2>/dev/null \
        | awk '/^rr_raft_is_leader\{group_id="1"\}/ {print $2}')"
  leaders=$(( leaders + ${v:-0} ))
done
if (( leaders == 1 )); then
  ok "C2: exactly one raft leader (inter-node mTLS replication works)"
else
  bad "C2: leader count = ${leaders}, expected 1"
fi

echo "==> [3/4] Transport probes (in-network, from the probe container)"
PROBE=("${COMPOSE[@]}" --profile selfcheck run --rm -T probe -c)

if "${PROBE[@]}" 'curl -fsS --max-time 5 http://kv-1:51001/ >/dev/null 2>&1'; then
  bad "N1: PLAINTEXT client was served on the TLS gRPC port"
else
  ok "N1: plaintext client rejected (no TLS → no service)"
fi

if "${PROBE[@]}" 'curl -sS --cacert /etc/rr/certs/ca.pem --max-time 5 https://kv-1:51001/ >/dev/null 2>&1'; then
  bad "N2: client WITHOUT certificate completed mTLS"
else
  ok "N2: TLS without client certificate rejected (mTLS enforced)"
fi

if "${PROBE[@]}" 'curl -sS --cacert /etc/rr/certs/ca.pem --cert /etc/rr/certs/client.pem --key /etc/rr/certs/client.key --max-time 5 -o /dev/null https://kv-1:51001/ >/dev/null 2>&1'; then
  ok "P1: TLS + client certificate accepted (positive control)"
else
  bad "P1: valid mTLS client was rejected"
fi

echo "==> [4/4] Result"
if (( FAIL > 0 )); then
  echo "SELFCHECK FAILED — ${FAIL} check(s) red, ${PASS} green"
  exit 1
fi
echo "SELFCHECK PASSED — ${PASS} checks green (stack behind G1–G7: TLS + mTLS + tokens, durable raft log)"
